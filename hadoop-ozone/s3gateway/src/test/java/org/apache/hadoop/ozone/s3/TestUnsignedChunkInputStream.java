package org.apache.hadoop.ozone.s3;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.Base64;
import java.util.stream.Stream;
import org.apache.commons.io.IOUtils;
import org.apache.hadoop.ozone.s3.SignedChunksInputStream.TrailerHeader;
import org.apache.hadoop.ozone.s3.exception.OS3Exception;
import org.apache.hadoop.ozone.s3.exception.S3ErrorTable;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.MethodSource;
import org.junit.jupiter.params.provider.ValueSource;

/**
 * Test {@link UnsignedChunksInputStream}.
 */
public class TestUnsignedChunkInputStream {

  private static final String KEY_PATH = "bucket/key";
  private static final String CONTENT = "1234567890abcde";
  // Generated by botocore's AwsChunkedWrapper with CRC32 and a 10-byte chunk size.
  private static final String BODY = "a\r\n1234567890\r\n5\r\nabcde\r\n0\r\n"
      + "x-amz-checksum-crc32:HydN+w==\r\n\r\n";

  @ParameterizedTest
  @CsvSource({"CRC32,AAAAAA==", "CRC32C,AAAAAA==", "CRC64NVME,AAAAAAAAAAA=",
      "SHA1,2jmj7l5rSw0yVb/vlWAYkK/YBwk=", "SHA256,47DEQpj8HBSa+/TImW+5JCeuQeRkm5NMpJWZG3hSuFU="})
  void emptyPayload(TrailerHeader header, String value) throws IOException {
    String body = "0\r\n" + header.getHeaderName() + ":" + value + "\r\n\r\n";
    try (UnsignedChunksInputStream stream = wrapContent(body, header)) {
      stream.verifyComplete();
      assertThat(stream.read()).isEqualTo(-1);
      assertThat(stream.getTrailerChecksum()).isEqualTo(Base64.getDecoder().decode(value));
    }
  }

  @ParameterizedTest
  @ValueSource(ints = {0, 1, 2, 10, 15, 64})
  void readAcrossChunks(int bufferSize) throws IOException {
    try (UnsignedChunksInputStream stream = wrapContent(BODY, TrailerHeader.CRC32)) {
      ByteArrayOutputStream result = new ByteArrayOutputStream();
      if (bufferSize == 0) {
        int value;
        while ((value = stream.read()) != -1) {
          result.write(value);
        }
      } else {
        byte[] buffer = new byte[bufferSize + 2];
        int length;
        while ((length = stream.read(buffer, 2, bufferSize)) != -1) {
          result.write(buffer, 2, length);
        }
      }
      assertThat(result.toString(UTF_8.name())).isEqualTo(CONTENT);
      assertThat(stream.getTrailerChecksum()).isEqualTo(Base64.getDecoder().decode("HydN+w=="));
      stream.verifyComplete();
      assertThat(stream.read()).isEqualTo(-1);
      assertThat(stream.read(new byte[1])).isEqualTo(-1);
      assertThat(stream.read(new byte[0])).isEqualTo(0);
    }
  }

  @ParameterizedTest
  @CsvSource({"CRC32,y/Q5Jg==",
      "CRC32C,4waSgw==",
      "CRC64NVME,rosUhgp5mIg=",
      "SHA1,98O8HYCOBHMq32eZZczDTKeuNEE=",
      "SHA256,FeKw08M4keuw8e9gnsQZQgwg4yDOlMZfvIwzEkSOsiU="})
  void verifiesPayloadChecksum(TrailerHeader header, String value) throws IOException {
    for (boolean singleByte : new boolean[]{false, true}) {
      for (boolean correct : new boolean[]{true, false}) {
        String payload = correct ? "123456789" : "123456780";
        String body = "4\r\n" + payload.substring(0, 4) + "\r\n5\r\n" + payload.substring(4)
            + "\r\n0\r\n" + header.getHeaderName() + ":" + value + "\r\n\r\n";
        try (UnsignedChunksInputStream stream = wrapContent(body, header)) {
          if (singleByte) {
            for (char expected : payload.toCharArray()) {
              assertThat(stream.read()).isEqualTo(expected);
            }
          } else {
            assertThat(IOUtils.readFully(stream, payload.length())).isEqualTo(payload.getBytes(UTF_8));
          }
          if (correct) {
            stream.verifyComplete();
            assertThat(stream.getTrailerChecksum()).isEqualTo(Base64.getDecoder().decode(value));
          } else {
            OS3Exception error = assertThrows(OS3Exception.class, stream::verifyComplete);
            assertThat(error.getCode()).isEqualTo(S3ErrorTable.BAD_DIGEST.getCode());
            assertThat(stream.getTrailerChecksum()).isNull();
          }
        }
      }
    }
  }

  @Test
  void exactLengthReadStillRequiresCompletion() throws IOException {
    ByteArrayInputStream original = new ByteArrayInputStream(BODY.getBytes(UTF_8));
    try (UnsignedChunksInputStream stream = new UnsignedChunksInputStream(original, KEY_PATH, TrailerHeader.CRC32)) {
      assertThat(IOUtils.readFully(stream, CONTENT.length())).isEqualTo(CONTENT.getBytes(UTF_8));
      assertThat(stream.getTrailerChecksum()).isNull();
      assertThat(original.available()).isPositive();

      stream.verifyComplete();
      assertThat(original.available()).isZero();
      byte[] checksum = stream.getTrailerChecksum();
      checksum[0] ^= 1;
      assertThat(stream.getTrailerChecksum()).isEqualTo(Base64.getDecoder().decode("HydN+w=="));
      stream.verifyComplete();
    }
  }

  @Test
  void skipConsumesDecodedPayload() throws IOException {
    try (UnsignedChunksInputStream stream = wrapContent(BODY, TrailerHeader.CRC32)) {
      assertThat(stream.skip(10)).isEqualTo(10);
      assertThat(IOUtils.toString(stream, UTF_8)).isEqualTo("abcde");
      assertThat(stream.getTrailerChecksum()).isEqualTo(Base64.getDecoder().decode("HydN+w=="));
    }
  }

  @ParameterizedTest
  @ValueSource(ints = {0, 5, 10, 14})
  void decodedLengthEndsBeforePayload(int length) throws IOException {
    try (UnsignedChunksInputStream stream = wrapContent(BODY, TrailerHeader.CRC32)) {
      IOUtils.readFully(stream, length);
      OS3Exception error = assertThrows(OS3Exception.class, stream::verifyComplete);
      assertThat(error.getCode()).isEqualTo(S3ErrorTable.INVALID_REQUEST.getCode());
      assertThat(error.getErrorMessage()).contains("Decoded content length ended before");
    }
  }

  @ParameterizedTest
  @ValueSource(booleans = {false, true})
  void rejectEveryTruncatedBody(boolean singleByte) throws IOException {
    for (int length = 0; length < BODY.length(); length++) {
      assertInvalidBody(BODY.substring(0, length), singleByte);
    }
  }

  static Stream<Arguments> malformedBodies() {
    return Stream.of(
        "0\r\n\r\n",
        "0\r\nx-amz-checksum-sha1:HydN+w==\r\n\r\n",
        "0\r\nx-amz-checksum-crc32 HydN+w==\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:not-base64\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:AAAA\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:AAAAAAAAAAA=\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:AAAAAA==\r\nx-amz-checksum-crc32:AAAAAA==\r\n\r\n",
        "0\r\nx-amz-checksum-crc32:AAAAAA==\r\n\r\nextra",
        "0\r\nx-amz-checksum-crc32:AAAAAA==\r\n\r\n\r\n",
        "1\r\naXX0\r\nx-amz-checksum-crc32:AAAAAA==\r\n\r\n",
        "1\r\na\rX0\r\nx-amz-checksum-crc32:AAAAAA==\r\n\r\n",
        "-1\r\n", "+1\r\n", "xyz\r\n", " 0\r\n", "0x0\r\n", "8000000000000000\r\n",
        "10000000000000000\r\n", "0;chunk-signature=abc\r\n",
        "A".repeat(8193) + "\r\n",
        "0\r\nx-amz-checksum-crc32:" + "A".repeat(8193) + "\r\n\r\n")
        .flatMap(body -> Stream.of(Arguments.of(body, false), Arguments.of(body, true)));
  }

  @ParameterizedTest
  @MethodSource("malformedBodies")
  void rejectMalformedBody(String body, boolean singleByte) throws IOException {
    assertInvalidBody(body, singleByte);
  }

  @ParameterizedTest
  @CsvSource({"CRC32,3", "CRC32C,5", "CRC64NVME,4", "SHA1,19", "SHA256,33"})
  void rejectWrongChecksumLength(TrailerHeader header, int length) throws IOException {
    String value = Base64.getEncoder().encodeToString(new byte[length]);
    try (UnsignedChunksInputStream stream = wrapContent("0\r\n" + header.getHeaderName() + ":" + value + "\r\n\r\n",
        header)) {
      OS3Exception error = assertThrows(OS3Exception.class, stream::verifyComplete);
      assertThat(error.getCode()).isEqualTo(S3ErrorTable.INVALID_REQUEST.getCode());
      assertThat(error.getErrorMessage()).contains(header.getHeaderName());
    }
  }

  @Test
  void acceptDocumentedOptionalLineFeed() throws IOException {
    String body = BODY.replace("x-amz-checksum-crc32:HydN+w==", "X-AMZ-CHECKSUM-CRC32:HydN+w==\n");
    try (UnsignedChunksInputStream stream = wrapContent(body, TrailerHeader.CRC32)) {
      assertThat(IOUtils.toString(stream, UTF_8)).isEqualTo(CONTENT);
    }
  }

  @Test
  void chunkLengthDoesNotRequireIntegerRangeOrAllocation() throws IOException {
    try (UnsignedChunksInputStream stream = wrapContent("80000000\r\na", TrailerHeader.CRC32)) {
      assertThat(stream.read()).isEqualTo('a');
      assertThrows(OS3Exception.class, stream::read);
    }
  }

  private void assertInvalidBody(String body, boolean singleByte) throws IOException {
    try (UnsignedChunksInputStream stream = wrapContent(body, TrailerHeader.CRC32)) {
      OS3Exception error = assertThrows(OS3Exception.class, () -> {
        if (singleByte) {
          int value;
          do {
            value = stream.read();
          } while (value != -1);
        } else {
          IOUtils.toByteArray(stream);
        }
      }, () -> "Accepted malformed body: " + body);
      assertThat(error.getCode()).isEqualTo(S3ErrorTable.INVALID_REQUEST.getCode());
      assertThat(stream.getTrailerChecksum()).isNull();
    }
  }

  private UnsignedChunksInputStream wrapContent(String content, TrailerHeader header) {
    return new UnsignedChunksInputStream(new ByteArrayInputStream(content.getBytes(UTF_8)), KEY_PATH, header);
  }
}
