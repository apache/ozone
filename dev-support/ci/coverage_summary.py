"""
Parse the JaCoCo XML report generated by coverage.sh and print a Markdown coverage summary.

Intended for GitHub Actions: coverage_summary.py [--report FILE] >> "$GITHUB_STEP_SUMMARY"

JaCoCo XML report structure (as produced for Ozone's all.xml):

<report name="...">
  <sessioninfo id="..." start="..." dump="..."/>   # one per test JVM
  <package name="org/apache/hadoop/ozone/om">
    <class name="org/apache/.../OzoneManager"      # include inner classes (Foo$Bar)
          sourcefilename="OzoneManager.java">
      <method name="<init>" desc="(...)V" line="70">
        <counter .../>
      </method>
      <counter .../>
    </class>
    <sourcefile name="OzoneManager.java">          # one per .java file
      <line nr="30" mi="0" ci="3" mb="0" cb="0"/>  # per-line: missed/covered
                                                   # instructions & branches
      <counter .../>
    </sourcefile>
    <counter .../>                                 # package totals
  </package>
  <counter .../>                                   # report (overall) totals
</report>

<counter type="LINE" missed="27270" covered="148570"/>
  type: INSTRUCTION | BRANCH | COMPLEXITY | LINE | METHOD | CLASS
  Ref: https://www.jacoco.org/jacoco/trunk/doc/counters.html

A counter is omitted when its total is 0 (e.g. a method with no branches), so a
missing counter means n/a, not 0% coverage.

Every level carries its own aggregated <counter> elements, so we read the direct
children of <report> instead of summing.
"""
import argparse
import dataclasses
import os
import sys
import xml.etree.ElementTree as ET

DEFAULT_REPORT = os.path.join("target", "coverage", "all.xml")

# INSTRUCTION and COMPLEXITY are left out on purpose: they track LINE and BRANCH
# within a fraction of a percent, so they would only add noise to the summary.
JACOCO_LINE = "LINE"
JACOCO_BRANCH = "BRANCH"
JACOCO_METHOD = "METHOD"
JACOCO_CLASS = "CLASS"


@dataclasses.dataclass
class Counter:
  missed: int = 0
  covered: int = 0

  @property
  def total(self):
    return self.missed + self.covered


@dataclasses.dataclass
class Coverage:
  """Counters of one JaCoCo report node, keyed by counter type."""
  name: str
  counters: dict

  def counter(self, counter_type):
    return self.counters.get(counter_type, Counter())

  @property
  def missed(self):
    # sort key for the package table: amount of untested code, not ratio, so tiny packages do not top the list
    return self.counter(JACOCO_LINE).missed + self.counter(JACOCO_BRANCH).missed

  @property
  def combined(self):
    # same formula as SonarCloud's "coverage" metric: (covered lines + covered conditions) / (lines + conditions),
    # where JaCoCo branches are Sonar's conditions
    lines, branches = self.counter(JACOCO_LINE), self.counter(JACOCO_BRANCH)
    return percent(lines.covered + branches.covered, lines.total + branches.total)


def percent(covered, total):
  return "%.1f%%" % (100.0 * covered / total) if total else "n/a"


def read_counters(elem):
  # Only the direct children: <package>, <class> and <method> nest their own counters.
  return {c.get("type"): Counter(int(c.get("missed") or 0), int(c.get("covered") or 0))
          for c in elem.findall("counter")}


def parse_report(xml_path):
  root = ET.parse(xml_path).getroot()
  return Coverage("", read_counters(root))


def render_summary(overall):
  lines, branches = overall.counter(JACOCO_LINE), overall.counter(JACOCO_BRANCH)
  out = ["## Coverage Summary", ""]
  out.append(f"**Overall coverage: {overall.combined}** (lines and branches combined, same formula as SonarCloud)")
  out.append("")
  out.append("|Counter|Coverage|Missed|Total|")
  out.append("|---|---|---|---|")
  out.append(f"|Lines|{percent(lines.covered, lines.total)}|{lines.missed}|{lines.total}|")
  out.append(f"|Branches|{percent(branches.covered, branches.total)}|{branches.missed}|{branches.total}|")
  out.append("")
  out.append(f"Untested: {overall.counter(JACOCO_METHOD).missed} methods, "
             f"{overall.counter(JACOCO_CLASS).missed} classes")
  out.append("")
  report_url = os.environ.get("COVERAGE_REPORT_URL")
  if report_url:
    out.extend([f"📦 Full HTML report: [download artifact]({report_url})", ""])
  return "\n".join(out) + "\n"


def main(argv=None):
  parser = argparse.ArgumentParser(description="Print a Markdown summary of a JaCoCo XML coverage report.")
  parser.add_argument("--report", default=DEFAULT_REPORT, help="path to the JaCoCo XML report")
  args = parser.parse_args(argv)

  overall = parse_report(args.report)
  print(render_summary(overall), end="")
  return 0


if __name__ == "__main__":
  sys.exit(main())
